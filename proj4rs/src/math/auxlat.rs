/// Third flattening n = (a - b) / (a + b) from the first eccentricity squared
#[inline]
pub(crate) fn third_flattening(es: f64) -> f64 {
    // n = (1 - b/a) / (1 + b/a) = es / (1 + sqrt(1 - es))^2
    es / (1. + (1. - es).sqrt()).powi(2)
}

/// Evaluate sum(p[i] * x^i, i, 0, N) via Horner's method.
#[inline]
pub(crate) fn polyval(x: f64, p: &[f64]) -> f64 {
    p.iter().rev().fold(0., |y, c| y * x + c)
}

/// Evaluate y = sum(c[k] * sin((2*k+2) * zeta), k, 0, K-1) by Clenshaw
/// summation. zeta is specified by its sine and cosine, szeta and czeta.
#[inline]
pub(crate) fn clenshaw(szeta: f64, czeta: f64, c: &[f64]) -> f64 {
    // Approx operation count = (K + 5) mult and (2 * K + 2) add
    let x = 2. * (czeta - szeta) * (czeta + szeta); // 2 * cos(2*zeta)
    let (u0, _) = c
        .iter()
        .rev()
        .fold((0., 0.), |(u0, u1), ck| (x * u0 - u1 + ck, u0));
    2. * szeta * czeta * u0 // sin(2*zeta) * u0
}

/// Compute the Fourier coefficients for a conversion between
/// any of phi, beta, theta and mu: the Taylor series are expansions in n^2
/// with the zero terms dropped.
pub(crate) fn coeffs_even(n: f64, coeffs: &[f64; 12]) -> AuxCoeffs {
    let n2 = n * n;
    let mut f = [0.; ORDER];
    let (mut d, mut o) = (n, 0);
    for (l, fl) in f.iter_mut().enumerate() {
        let m = (ORDER - l - 1) / 2; // order of polynomial in n^2
        *fl = d * polyval(n2, &coeffs[o..=o + m]);
        o += m + 1;
        d *= n;
    }
    f
}

/// Compute the Fourier coefficients for a conversion involving
/// chi or xi: the Taylor series are full expansions in n.
pub(crate) fn coeffs_full(n: f64, coeffs: &[f64; 21]) -> AuxCoeffs {
    let mut f = [0.; ORDER];
    let (mut d, mut o) = (n, 0);
    for (l, fl) in f.iter_mut().enumerate() {
        let m = ORDER - l - 1; // order of polynomial in n
        *fl = d * polyval(n, &coeffs[o..=o + m]);
        o += m + 1;
        d *= n;
    }
    f
}

/// Convert auxiliary latitude zeta to eta, given the coefficients
/// for that conversion. The sine and cosine of zeta are given as inputs.
#[inline]
pub(crate) fn convert(zeta: f64, szeta: f64, czeta: f64, f: &AuxCoeffs) -> f64 {
    zeta + clenshaw(szeta, czeta, f)
}

/// Compute the rectifying radius = quarter meridian / (pi/2 * a).
pub(crate) fn rectifying_radius(n: f64) -> f64 {
    // Expansion of (quarter meridian) / ((a+b)/2 * pi/2) as series in n^2;
    // these coefficients are ( (2*k - 3)!! / (2*k)!! )^2 for k = 0..3
    const COEFF_RAD: [f64; 4] = [1., 1. / 4., 1. / 64., 1. / 256.];
    polyval(n * n, &COEFF_RAD) / (1. + n)
}
