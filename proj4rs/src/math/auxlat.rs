//!
//! Conversions between auxiliary latitudes
//!
//! Series expansions in the third flattening n, adapted from PROJ `src/latitudes.cpp`
//! (PROJ >= 9.7) which is itself adapted from
//!
//!   C. F. F. Karney, On auxiliary latitudes,
//!   Survey Review 56, 165-180 (2024)
//!   <https://doi.org/10.1080/00396265.2023.2217604>
//!   Preprint: <https://arxiv.org/abs/2212.05818>
//!
//! The conversions are Fourier series in the auxiliary latitude where each
//! coefficient is given as a Taylor series in n truncated at order 6.
//! This suffices to give full double precision accuracy for |f| <= 1/150.
//!
//! Only the conversions needed by proj4rs are included:
//!
//! * phi <-> mu for meridian distance
//! * phi <-> xi for authalic latitude conversions
//!

/// The order of the expansion in n
pub(crate) const ORDER: usize = 6;

/// Fourier coefficients for converting one auxiliary latitude to another
pub(crate) type AuxCoeffs = [f64; ORDER];

